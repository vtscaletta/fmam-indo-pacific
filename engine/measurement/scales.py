"""
Шкалы приведения наблюдений к отрезку [0, 1].

Назначение слоя. Наблюдения приходят в разных единицах, а именно в днях,
случаях, долях, ступенях и денежных величинах, тогда как контроллер
принимает на вход числа от нуля до единицы. Здесь собраны правила
преобразования и только они.

Что модуль знает. Правила пересчёта.
Чего модуль не знает. Ни агентов, ни годов, ни названий индикаторов, ни
источников данных. Всякая функция принимает числа и возвращает числа.

Три сквозных требования.

Первое. Границы приведения задаются определением показателя, а не
наблюдённой выборкой. Функции принимают границы явными аргументами и сами
их не выводят, вследствие чего подгонка под выборку невозможна по
устройству модуля.

Второе. Отсутствие наблюдения обозначается NaN и нулём не подменяется.
Ноль есть осмысленное значение шкалы и означает нижний предел, тогда как
отсутствие значения не означает ничего.

Третье. Всякая функция чиста, то есть не хранит состояния и при одинаковых
входах всегда возвращает одинаковый выход.
"""
from __future__ import annotations

import math


NA = float("nan")


def is_missing(x: float | None) -> bool:
    """Отсутствует ли наблюдение."""
    return x is None or (isinstance(x, float) and math.isnan(x))


def _clamp(x: float) -> float:
    """Прижимает значение к отрезку [0, 1]."""
    return 0.0 if x < 0.0 else (1.0 if x > 1.0 else x)


def linear(value: float | None, low: float, high: float) -> float:
    """
    Линейное приведение по двум реперным точкам.

    Применяется к счётным показателям, где известны нижний и верхний
    пределы, заданные определением. Пример, дни присутствия судов в
    прилежащей зоне при low равном нулю и high равном 365.

    Значения вне отрезка прижимаются к границам, поскольку выход за предел
    означает достижение предела, а не превышение смысла показателя.

    Границы могут идти по убыванию, то есть low больше high. Так задаётся
    обращённая шкала, где большему наблюдению соответствует меньшее
    значение переменной. Пример, доля населения, испытывающего близость к
    противнику, при low равном 100 и high равном 0.
    """
    if is_missing(value):
        return NA
    if low == high:
        raise ValueError("Реперные точки совпадают, шкала не определена")
    return _clamp((float(value) - low) / (high - low))


def share(own: float | None, other: float | None) -> float:
    """
    Доля второй величины в сумме двух.

    Применяется там, где показатель есть соотношение двух сопоставимых
    величин. Пример, доля военных расходов противника в сумме расходов
    пары. Результат лежит в отрезке по построению, равен половине при
    равенстве величин и растёт при усилении второй стороны.

    Дополнительного приведения не требует, вследствие чего реперные точки
    для такого показателя не назначаются вовсе.
    """
    if is_missing(own) or is_missing(other):
        return NA
    total = float(own) + float(other)
    if total <= 0.0:
        return NA
    return _clamp(float(other) / total)


def ordinal(step: int | None, n_steps: int, *, inverted: bool = False) -> float:
    """
    Приведение порядкового разряда к числу.

    Разряды упорядочены, однако расстояние между ними неизвестно и ни одним
    источником не сообщается. Разрядам присваиваются поэтому значения,
    отстоящие друг от друга поровну, что не требует ни одного
    дополнительного допущения.

    При n разрядах промежутков между ними n минус один, отчего каждый
    промежуток равен единице, делённой на n минус один. Пример для четырёх
    разрядов, значения 0, 1/3, 2/3 и 1.

    Аргумент inverted обращает шкалу. Он нужен там, где старший разряд
    означает меньшее значение переменной. Пример, ступень правового
    потолка, где наиболее крепкий потолок означает наименьшую эрозию.
    """
    if step is None:
        return NA
    if n_steps < 2:
        raise ValueError("Разрядов должно быть не менее двух")
    if not 0 <= step <= n_steps - 1:
        raise ValueError(f"Разряд {step} вне диапазона 0..{n_steps - 1}")
    value = step / (n_steps - 1)
    return 1.0 - value if inverted else value


def count_of(observed: float | None, total: float) -> float:
    """
    Доля наблюдённого числа от полного перечня.

    Применяется там, где верхний предел задан числом позиций закрытого
    перечня, а не наблюдением. Пример, число снятых запретов из пяти,
    каждый из которых установлен датированным актом.
    """
    if is_missing(observed):
        return NA
    if total <= 0:
        raise ValueError("Полный перечень не может быть пустым либо отрицательным")
    return _clamp(float(observed) / float(total))


def deviation_from_baseline(value: float | None, baseline: float,
                            spread: float) -> float:
    """
    Отклонение наблюдения от собственного обычного уровня.

    Применяется к переменной доверия. Уровень опоры на внешнюю гарантию,
    обычный для государства договорного типа, для хеджирующего был бы
    небывало высоким, вследствие чего сравнение агентов по абсолютной
    величине лишено смысла. Показатель измеряет поэтому, насколько текущее
    положение отличается от привычного для данного агента.

    Обычный уровень baseline и разброс spread вычисляются по всему
    интервалу наблюдения для каждого агента отдельно и передаются сюда
    готовыми. Половина шкалы соответствует привычному положению, значения
    ниже половины означают положение хуже привычного.

    Приём известен как приведение относительно эталона и применяется в
    методике композитных показателей наряду с приведением к крайним точкам.
    """
    if is_missing(value):
        return NA
    if spread <= 0.0:
        return 0.5
    z = (float(value) - baseline) / spread
    return _clamp(0.5 + 0.5 * max(-1.0, min(1.0, z)))


def invert(value: float | None) -> float:
    """
    Обращение шкалы уже приведённого значения.

    Применяется там, где показатель измерен в одну сторону, а переменная
    требует противоположной. Пример, доля согласия аудитории при
    необходимости получить долю несогласия.
    """
    if is_missing(value):
        return NA
    return _clamp(1.0 - float(value))
