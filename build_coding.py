"""
Сборка материалов для кодирования.

Производит три вещи.
  1. Текстовый файл для кодировщика, где сверху правила, ниже единицы в
     перемешанном порядке. Порядок задан зерном и потому воспроизводим.
  2. Таблицу для внесения ответов трёх кодировщиков.
  3. Перечень исключённых единиц с основанием исключения.

Единицы предъявляются без указания того, к какому разряду отнесены их
записи, поскольку разряд есть суждение составителя, а не сведение о
событии.
"""
from __future__ import annotations

import random
from pathlib import Path

import pandas as pd

from engine.measurement.dossier import (
    CODEABLE, CODING_YEARS, by_unit, load_events, unit_status,
)
from engine.measurement.loaders import load_agents

SEED = 20260101
OUT = Path("/mnt/user-data/outputs")

RULES = """ПРАВИЛА КОДИРОВАНИЯ УРОВНЯ ВРАЖДЕБНОСТИ
Второй круг. Изменения относительно первого круга помечены словом ИЗМЕНЕНО.

1. ЗАДАЧА

Для каждой единицы присвоить одно число от 0 до 4 по правилам ниже.

2. ЕДИНИЦА КОДИРОВАНИЯ

Единицу образует государство в отдельно взятом году. Заголовок единицы
даёт её обозначение, название государства и год.

Кодируется наивысший уровень враждебности, достигнутый в этом году в любом
споре данного государства с любым другим.

ВАЖНО. Государство выступает участником спора независимо от того,
действовало ли оно само либо действия совершались против него. Столкновение
двух государств даёт обоим один и тот же уровень. Вопрос о том, кто начал,
не задаётся и на уровень не влияет.

3. ШКАЛА

  0  Милитаризованных действий не было.
     Сюда относятся дипломатические протесты, заявления, ноты, вызовы
     послов, экономические меры, судебные разбирательства, приостановка
     переговоров и соглашений.

  1  Угроза применения силы.
     Угроза применить силу, угроза блокады, угроза занять территорию,
     угроза объявить войну, угроза применить оружие массового поражения,
     угроза вступить в войну.

  2  Демонстрация силы.
     Демонстрация силы, приведение в боевую готовность, ядерная тревога,
     мобилизация, укрепление границы, нарушение границы.
     Нарушением границы считается вход в территориальные воды либо в
     территориальное воздушное пространство другого государства, а также
     пересечение сухопутной границы или линии разграничения.

  3  Применение силы.
     Блокада, занятие территории, захват судна либо лица, нападение,
     столкновение, объявление войны, применение оружия массового
     поражения.
     ИЗМЕНЕНО. К этому уровню отнесены также применение водомёта, таран,
     навал и иное физическое воздействие на судно либо летательный аппарат,
     повлёкшее повреждение, ранение либо вынужденное изменение курса.
     ИЗМЕНЕНО. Захватом считается также задержание судна с досмотром либо
     уводом, произведённое силами другого государства.

  4  Война.
     Начало межгосударственной войны, вступление в идущую войну.

4. ПОРЯДОК ДЕЙСТВИЙ

Отвечать на четыре вопроса подряд, прекращая на первом утвердительном
ответе.

  1. Есть ли в изложении хотя бы одно действие из перечня уровней 1-4.
     Нет, поставить 0 и перейти к следующей единице. Да, к вопросу 2.
  2. Есть ли действие уровня 4. Да, поставить 4. Нет, к вопросу 3.
  3. Есть ли действие уровня 3. Да, поставить 3. Нет, к вопросу 4.
  4. Есть ли действие уровня 2. Да, поставить 2. Нет, поставить 1.

Уровень определяется наивысшим действием, а не их числом и не их
продолжительностью.

5. ПОГРАНИЧНЫЕ ПРАВИЛА

Применять буквально. Собственным знанием предмета не восполнять и
расширительно не толковать.

  ПЕРВОЕ. Действие засчитывается тому году, в котором совершалось.
  Занятие территории, начатое ранее и не прекращённое, засчитывается
  каждому году, покуда продолжается. Неурегулированность спора сама по
  себе действием не является.

  ВТОРОЕ. Учения засчитываются как демонстрация силы лишь при наличии в
  изложении одного из трёх признаков, а именно отступления от ранее
  утверждённого расписания, внепланового развёртывания сил либо заявления
  ведомства о созыве манёвров в связи с конкретным событием.
  Ежегодные учения, объявленные заранее, не засчитываются даже при
  совпадении их сроков с обострением. Совпадение сроков признаком не
  является.

  ТРЕТЬЕ. ИЗМЕНЕНО ЦЕЛИКОМ. Правило разводит два пространства.
     а) Прилежащая зона, исключительная экономическая зона и
        опознавательная зона противовоздушной обороны суверенитету не
        подчинены. Присутствие судов и летательных аппаратов в них само
        по себе не засчитывается, сколь бы длительным оно ни было.
        Засчитывается лишь присутствие, сопровождённое одним из четырёх
        действий, а именно перехватом либо блокированием чужого судна или
        воздушного судна, применением водомётов, лазеров или иных средств
        воздействия, отказом покинуть пространство в ответ на прямое
        требование другой стороны либо манёвром, создавшим опасность
        столкновения.
     б) Территориальные воды и территориальное воздушное пространство
        подчинены суверенитету. Вход в них образует нарушение границы и
        даёт уровень 2 сам по себе, без дополнительных действий.
        Если вход сопровождался действием уровня 3, ставится 3.

  ЧЕТВЁРТОЕ. Пуск ракеты засчитывается как демонстрация силы при наличии
  указания на пролёт над территорией другого государства либо на падение
  в пределах его исключительной экономической зоны. Пуск, о котором
  известно лишь то, что он состоялся, не засчитывается.

  ПЯТОЕ. Действия негосударственных участников засчитываются государству
  при наличии указания на сопровождение их судами либо летательными
  аппаратами государственных ведомств, на управление их действиями со
  стороны ведомства либо на их снабжение ведомством. Признание
  государством такого участника своим не требуется.

  ШЕСТОЕ. Экономические меры, включая запреты на ввоз и вывоз,
  ограничения на передвижение граждан, отзыв разрешений и приостановку
  соглашений, милитаризованными действиями не являются и дают 0
  независимо от их тяжести и последствий.

  СЕДЬМОЕ. Средства воздействия, не названные в перечнях уровней, дают 0.
  Сюда относятся подавление сигналов спутниковой навигации, запуск
  воздушных шаров, распространение сведений и подобное. Перечни составлены
  ранее появления этих средств и расширению не подлежат.

6. ОТСУТСТВИЕ СВЕДЕНИЙ

Единица, изложение которой не содержит ни одного действия из перечней,
получает 0. Часть единиц содержит описание длящегося порядка без указания
на отдельные действия. Такие единицы кодируются по правилу третьему.

7. ФОРМА ОТВЕТА

Возвращать только строки вида обозначение, знак равенства, число.
Пояснений, оговорок, промежуточных и дробных значений не давать.
Обозначение переписывать в точности как в заголовке единицы.

Пример ответа.

  jpn-2018 = 3
  aus-2022 = 2
  ind-2019 = 0
"""


def build():
    agents = load_agents("data/agents.csv")
    events = load_events("data/events.csv", agents)
    status = unit_status(events, agents)
    units = by_unit(events, agents, only=CODEABLE)

    keys = [k for k in sorted(status) if status[k] != "объявленный пробел"]
    excluded = [k for k in sorted(status) if status[k] == "объявленный пробел"]

    rnd = random.Random(SEED)
    shuffled = list(keys)
    rnd.shuffle(shuffled)

    lines = [RULES, "", "=" * 70, "",
             f"ЕДИНИЦЫ, ВСЕГО {len(shuffled)}", ""]
    for code, year in shuffled:
        ident = f"{code}-{year}"
        name = agents[code].name
        lines.append(f"[{ident}] {name}, {year} год.")
        evs = units[(code, year)]
        if not evs:
            lines.append("  Задокументированных действий не приводится.")
        for e in evs:
            other = e.agent_b if e.agent_a == code else e.agent_a
            lines.append(f"  {e.date}. Вторая сторона {agents[other].name}. "
                         f"{e.description}")
        lines.append("")

    text = "\n".join(lines)
    (OUT / "Материал для кодирования.txt").write_text(text, encoding="utf-8")

    ans = pd.DataFrame({
        "идентификатор": [f"{c}-{y}" for c, y in shuffled],
        "автор": "",
        "модель_1": "",
        "модель_2": "",
    })
    exc = pd.DataFrame({
        "идентификатор": [f"{c}-{y}" for c, y in excluded],
        "основание": "Поиск признан недостаточным, единица кодированию "
                     "не подлежит",
    })
    with pd.ExcelWriter(OUT / "Ответы кодировщиков.xlsx",
                        engine="openpyxl") as w:
        ans.to_excel(w, sheet_name="ответы", index=False)
        exc.to_excel(w, sheet_name="исключённые", index=False)
        for sh, width in (("ответы", 18), ("исключённые", 18)):
            ws = w.sheets[sh]
            ws.column_dimensions["A"].width = width
            ws.column_dimensions["B"].width = 60 if sh == "исключённые" else 12
            ws.column_dimensions["C"].width = 12
            ws.column_dimensions["D"].width = 12

    print("единиц к кодированию:", len(shuffled))
    print("исключено:", len(excluded))
    print("знаков в материале:", len(text))
    print("порций по двадцать пять:", (len(shuffled) + 24) // 25)
    return shuffled, excluded


if __name__ == "__main__":
    build()
