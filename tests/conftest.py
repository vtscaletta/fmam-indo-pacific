"""
Настройка путей поиска для испытаний.

Затруднение. Испытания ввозят движок именами вида `engine.simulator`, тогда
как папка, в которой движок лежит, к путям поиска сама собою не добавляется.
При запуске через `python -m pytest` текущая папка добавляется толкователем,
при запуске же командой `pytest` не добавляется, отчего всякое испытание
обрывается сообщением о ненайденной единице `engine`.

Решение. Настоящая единица выполняется pytest прежде всех испытаний,
поскольку лежит в корне и носит условленное имя. Она добавляет корень
хранилища к путям поиска явно, отчего оба способа запуска становятся
равносильными при всякой версии pytest.

Способ выбран взамен объявления `pythonpath` в настройке, поскольку то
объявление появилось лишь в седьмой версии pytest и на более ранних молча
не действует.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
