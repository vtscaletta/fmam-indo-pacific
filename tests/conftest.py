"""
Настройка путей поиска для испытаний.

Затруднение. Испытания ввозят движок именами вида `engine.simulator`, тогда
как папка, в которой движок лежит, к путям поиска сама собою не добавляется.
При запуске через `python -m pytest` текущая папка добавляется толкователем,
при запуске же командой `pytest` не добавляется, отчего всякое испытание
обрывается сообщением о ненайденной единице `engine`.

Решение. Настоящая единица лежит рядом с испытаниями и потому подхватывается
pytest всегда, независимо от того, откуда запуск и какая корневая папка
определена. Она добавляет папку уровнем выше, то есть корень хранилища, к
путям поиска явно.

Помещение в папку испытаний, а не в корень, выбрано намеренно. Единица в
корне подхватывается лишь тогда, когда pytest признал корень корневым, что
зависит от наличия прочих настроечных единиц и потому надёжным не является.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
